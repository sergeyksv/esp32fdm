#!/usr/bin/env python3
"""Write build_info.c with the build stamp: "16.11.26 14:32 deee079+".

The time tells two flashes apart, the commit says what code it is, and "+"
means there were uncommitted changes.  Run on every build; the file is only
rewritten when the stamp changes, so an unchanged minute recompiles nothing.
The "FWBUILD=" tag lets the OTA code find the stamp in an uploaded image.
"""
import subprocess
import sys
import time


def git(*args):
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def main():
    out = sys.argv[1]
    commit = git("rev-parse", "--short=7", "HEAD") or "nogit"
    if git("status", "--porcelain"):
        commit += "+"
    stamp = time.strftime("%d.%m.%y %H:%M") + " " + commit
    text = ('/* Generated by tools/build_stamp.py */\n'
            'const char FW_BUILD_TAG[] = "FWBUILD=%s";\n'
            'const char *const FW_BUILD = FW_BUILD_TAG + 8;\n' % stamp)
    try:
        with open(out) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
